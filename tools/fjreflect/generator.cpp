#include "generator.hpp"

#include <filesystem>
#include <fstream>
#include <iostream>

namespace fjreflect {

static void write_generated_cpp(const ComponentInfo& comp,
                                 const std::string& output_dir) {
    auto stem = std::filesystem::path(comp.source_file).stem().string();
    auto path = output_dir + "/" + stem + ".generated.cpp";

    std::ofstream out(path);
    if (!out) {
        std::cerr << "fjreflect: cannot write " << path << "\n";
        return;
    }

    out << "// " << stem << ".generated.cpp — Generated by fjreflect. Do not edit.\n";
    out << "#include \"fjell/api.h\"\n";
    out << "#include <cstdint>\n\n";

    // Declare trace bridge functions if needed
    bool has_weak = false, has_ref = false, has_shared = false;
    for (const auto& f : comp.fields) {
        if (f.fj_field_type == "FJELL_FIELD_WEAK_REF") has_weak = true;
        if (f.fj_field_type == "FJELL_FIELD_REF") has_ref = true;
        if (f.fj_field_type == "FJELL_FIELD_SHARED_REF") has_shared = true;
    }
    if (has_weak) out << "extern \"C\" void fjell_gc_trace_weak(void*, void*);\n";
    if (has_ref) out << "extern \"C\" void fjell_gc_trace_ref(void*, void*);\n";
    if (has_shared) out << "extern \"C\" void fjell_gc_trace_shared(void*, void*);\n";
    if (has_weak || has_ref || has_shared) out << "\n";

    // Field table
    out << std::fixed;
    out << "extern \"C\" const FjellFieldDesc fjreflect_" << comp.class_name << "_fields[] = {\n";
    for (const auto& f : comp.fields) {
        out << "    {\"" << f.name << "\", " << f.fj_field_type
            << ", " << f.offset << ", " << f.size
            << ", nullptr, " << f.hint_min << "f, " << f.hint_max << "f, " << f.hint_speed << "f, ";
        if (f.ref_target.empty()) {
            out << "nullptr";
        } else {
            out << "\"" << f.ref_target << "\"";
        }
        out << "},\n";
    }
    out << "};\n\n";

    // Field count
    out << "extern \"C\" const uint32_t fjreflect_" << comp.class_name
        << "_field_count = " << comp.fields.size() << ";\n\n";

    // Trace function
    bool has_refs = has_weak || has_ref || has_shared;
    if (has_refs) {
        out << "extern \"C\" void fjreflect_" << comp.class_name
            << "_trace(void* instance, void* visitor) {\n";
        out << "    char* base = static_cast<char*>(instance);\n";
        out << "    (void)visitor;\n";
        for (const auto& f : comp.fields) {
            if (f.fj_field_type == "FJELL_FIELD_WEAK_REF") {
                out << "    fjell_gc_trace_weak(visitor, base + " << f.offset << ");\n";
            } else if (f.fj_field_type == "FJELL_FIELD_REF") {
                out << "    fjell_gc_trace_ref(visitor, base + " << f.offset << ");\n";
            } else if (f.fj_field_type == "FJELL_FIELD_SHARED_REF") {
                out << "    fjell_gc_trace_shared(visitor, base + " << f.offset << ");\n";
            }
        }
        out << "}\n";
    } else {
        // No ref fields — emit a null-able trace (won't be registered)
        out << "// No reference fields — no trace function needed.\n";
    }
}

static void write_verify_cpp(const ComponentInfo& comp,
                               const std::string& output_dir) {
    auto stem = std::filesystem::path(comp.source_file).stem().string();
    auto path = output_dir + "/" + stem + ".verify.cpp";

    std::ofstream out(path);
    if (!out) return;

    out << "// " << stem << ".verify.cpp — Layout verification. Generated by fjreflect.\n";
    auto source_filename = std::filesystem::path(comp.source_file).filename().string();
    out << "#include \"" << source_filename << "\"\n";
    out << "#include <cstddef>\n\n";

    for (const auto& f : comp.fields) {
        out << "static_assert(offsetof(" << comp.qualified_name << ", " << f.name
            << ") == " << f.offset << ", \"fjreflect layout mismatch: "
            << comp.qualified_name << "::" << f.name << "\");\n";
    }
}

static void write_manifest(const std::vector<ComponentInfo>& components,
                            const std::string& output_dir) {
    auto path = output_dir + "/manifest.json";
    std::ofstream out(path);
    if (!out) {
        std::cerr << "fjreflect: cannot write " << path << "\n";
        return;
    }

    out << "{\n  \"types\": [\n";
    for (size_t i = 0; i < components.size(); ++i) {
        const auto& comp = components[i];
        bool has_refs = false;
        for (const auto& f : comp.fields) {
            if (f.fj_field_type.find("REF") != std::string::npos) {
                has_refs = true;
                break;
            }
        }

        out << "    {\n";
        out << "      \"name\": \"" << comp.class_name << "\",\n";
        out << "      \"fields_symbol\": \"fjreflect_" << comp.class_name << "_fields\",\n";
        out << "      \"field_count\": " << comp.fields.size() << ",\n";
        if (has_refs) {
            out << "      \"trace_symbol\": \"fjreflect_" << comp.class_name << "_trace\"\n";
        } else {
            out << "      \"trace_symbol\": null\n";
        }
        out << "    }";
        if (i + 1 < components.size()) out << ",";
        out << "\n";
    }
    out << "  ]\n}\n";
}

void generate(const std::vector<ComponentInfo>& components,
              const GenerateOptions& opts) {
    std::filesystem::create_directories(opts.output_dir);

    for (const auto& comp : components) {
        write_generated_cpp(comp, opts.output_dir);
        write_verify_cpp(comp, opts.output_dir);
    }

    write_manifest(components, opts.output_dir);
}

} // namespace fjreflect
